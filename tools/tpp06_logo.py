#!/usr/bin/env python3
"""Offline 320x480 boot-logo codec. No device access, erase, flash or reboot.

Converts an already rendered opaque PNG to a 512 KiB partition image.
The caller must explicitly select RGB565 or BGR565; it is never guessed.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat
import struct

WIDTH, HEIGHT = 320, 480
PAYLOAD_SIZE = WIDTH * HEIGHT * 2
PARTITION_SIZE = 512 * 1024


def encode(rgb, order):
    if order not in ("RGB565", "BGR565"):
        raise ValueError("Explicit RGB565 or BGR565 pixel order required")
    if len(rgb) != WIDTH * HEIGHT * 3:
        raise ValueError("Exactly 320x480 RGB bytes required")
    out = bytearray()
    for r, g, b in zip(rgb[0::3], rgb[1::3], rgb[2::3]):
        high, low = (r, b) if order == "RGB565" else (b, r)
        out.extend(struct.pack("<H", ((high >> 3) << 11) | ((g >> 2) << 5) | (low >> 3)))
    out.extend(b"\xff" * (PARTITION_SIZE - len(out)))
    return bytes(out)


def decode(data, order):
    if order not in ("RGB565", "BGR565"):
        raise ValueError("Explicit RGB565 or BGR565 pixel order required")
    if len(data) != PARTITION_SIZE:
        raise ValueError("Expected exactly 512 KiB")
    if data[PAYLOAD_SIZE:] != b"\xff" * (PARTITION_SIZE - PAYLOAD_SIZE):
        raise ValueError("Unexpected data after logo: refuse to overwrite unknown format")
    rgb = bytearray()
    for (pixel,) in struct.iter_unpack("<H", data[:PAYLOAD_SIZE]):
        high, green, low = (pixel >> 11) * 255 // 31, ((pixel >> 5) & 63) * 255 // 63, (pixel & 31) * 255 // 31
        rgb.extend((high, green, low) if order == "RGB565" else (low, green, high))
    return bytes(rgb)


def write_new_regular(path, data):
    # Refuse /dev, symlinks and all existing paths. This is an offline codec,
    # deliberately not a shortcut for writing the generated bytes to an MTD.
    path = Path(path)
    parent = path.parent.resolve(strict=True)
    if parent == Path("/dev") or Path("/dev") in parent.parents:
        raise ValueError("Device paths are forbidden")
    target = parent / path.name
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "wb") as stream:
        if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
            raise ValueError("Regular output files only")
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("png", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--pixel-order", choices=("RGB565", "BGR565"), required=True)
    args = parser.parse_args()
    from PIL import Image
    with Image.open(args.png) as picture:
        if picture.format != "PNG" or picture.size != (WIDTH, HEIGHT):
            raise ValueError("Provide a 320x480 PNG; no implicit resizing")
        rgba = picture.convert("RGBA")
        if rgba.getchannel("A").getextrema() != (255, 255):
            raise ValueError("Render on an opaque background first")
        raw = encode(picture.convert("RGB").tobytes(), args.pixel_order)
    decode(raw, args.pixel_order)  # Validate partition geometry and padding.
    write_new_regular(args.output, raw)
    print(json.dumps({"output": str(args.output), "bytes": len(raw),
                      "payload_bytes": PAYLOAD_SIZE, "pixel_order": args.pixel_order,
                      "sha256": hashlib.sha256(raw).hexdigest(), "flashed": False}))


if __name__ == "__main__":
    main()
